import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from '../gui/node_modules/typescript/lib/typescript.js';
const source=fs.readFileSync(new URL('../gui/src/lib/resources/PerceptionSavedEditor.svelte',import.meta.url),'utf8');
const ast=ts.createSourceFile('component.ts',source.match(/<script lang="ts">([\s\S]*?)<\/script>/)[1],ts.ScriptTarget.Latest,true);
const functions=['canLeave','beforeUnload'].map(name=>ast.statements.find(n=>ts.isFunctionDeclaration(n)&&n.name?.text===name).getText(ast)).join('\n');
const code=ts.transpileModule(functions,{compilerOptions:{target:ts.ScriptTarget.ESNext}}).outputText;
let held=[];
const h=new Function('store',`let leaveError='';${code};return {canLeave,beforeUnload,error:()=>leaveError}`)({unsettledTargets:()=>held});
const close=()=>{const e=new Event('beforeunload',{cancelable:true});h.beforeUnload(e);return e.defaultPrevented;};
assert.equal(close(),false);
held=[{instance:'VAC-A',profile:'hidden-profile'}];
assert.equal(h.canLeave(),false);
assert.equal(close(),true);
assert.match(h.error(),/VAC-A \/ hidden-profile/);
held=[];assert.equal(close(),false);assert.equal(h.error(),'');
assert.ok(source.includes('onbeforeunload={beforeUnload}'));
assert.ok(source.includes('guardLeaving(canLeave)'));
assert.ok(!functions.includes('window.confirm'));
console.log('Perception close guard: hidden target blocks navigation and shutdown event; settled state releases both without confirm dialog.');
