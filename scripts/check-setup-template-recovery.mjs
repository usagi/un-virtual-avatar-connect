import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from '../gui/node_modules/typescript/lib/typescript.js';
const source = fs.readFileSync(new URL('../gui/src/lib/SetupExperience.svelte', import.meta.url),'utf8');
const script = source.match(/<script lang="ts">([\s\S]*?)<\/script>/)[1];
const ast=ts.createSourceFile('setup.ts',script,ts.ScriptTarget.Latest,true);
const functions=ast.statements.filter(n=>ts.isFunctionDeclaration(n)&&['loadTemplates','message'].includes(n.name.text));
assert.equal(functions.length,2);
const code=ts.transpileModule(functions.map(n=>n.getText(ast)).join('\n'),{compilerOptions:{target:ts.ScriptTarget.ESNext}}).outputText;
let calls=0, reply=()=>Promise.reject(Error('offline'));
const model=new Function('api',`
 let templates=[],templatesLoading=false,templatesError=null,busy=false,selectedTemplateId=null;
 let label='My entered name',importSource={name:'my.zip'},error='Existing save error';
 ${code}
 return {loadTemplates,state:()=>({templates,templatesLoading,templatesError,selectedTemplateId,label,importSource,error}),select:id=>selectedTemplateId=id,setBusy:value=>busy=value};
`)({desktopProfileTemplates:()=>{calls++;return reply();}});
await model.loadTemplates();
assert.match(model.state().templatesError,/offline/);
assert.equal(model.state().templatesLoading,false);
let resolve;
reply=()=>new Promise(r=>resolve=r);
const pending=model.loadTemplates();
await model.loadTemplates();
assert.equal(calls,2,'duplicate click must not send another request');
resolve([{id:'ai',recommended:true},{id:'no-ai'}]);
await pending;
assert.equal(model.state().selectedTemplateId,'ai');
assert.equal(model.state().templatesError,null);
model.select('no-ai');
reply=()=>Promise.resolve([{id:'ai',recommended:true},{id:'no-ai'}]);
await model.loadTemplates();
assert.equal(model.state().selectedTemplateId,'no-ai');
assert.equal(model.state().label,'My entered name');
assert.equal(model.state().importSource.name,'my.zip');
assert.equal(model.state().error,'Existing save error');
model.setBusy(true);
await model.loadTemplates();
assert.equal(calls,3);
model.setBusy(false);
reply=()=>Promise.resolve([]);
await model.loadTemplates();
assert.equal(model.state().selectedTemplateId,null);
assert.match(model.state().templatesError,/見つかりません/);
assert.match(source,/onMount\(\(\) => \{\s*void loadTemplates\(\)/);
assert.match(source,/onclick=\{\(\) => void loadTemplates\(\)\}/);
console.log('PASS setup template failure/retry, duplicate request, retained selection/input/error, busy guard and empty list');
